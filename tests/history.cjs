const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../staff.php'), 'utf8');
const start = source.indexOf('        function escapeTimelineText(');
const end = source.indexOf('        function toggleInternalHistory()', start);
const context = vm.createContext({});
vm.runInContext(source.slice(start, end), context);
const format = context.formatTimelineNotes;
assert.match(format(null), /No note entries/);
assert.match(format(' \n\r\n'), /No note entries/);
const html = format('2026-10-20 09:00 - <img src=x onerror=alert(1)> | x@example.com - Old <script>alert(1)</script>\nContinuation <b>line</b>\n2026-10-21 10:00 - Agent - Latest');
assert.ok(html.indexOf('Latest') < html.indexOf('Old &lt;script&gt;'));
assert.ok(!html.includes('<script>') && !html.includes('<img'));
assert.match(html, /Continuation &lt;b&gt;line&lt;\/b&gt;/);
assert.match(html, /2 entries/);
assert.match(format('<svg onload=alert(1)>'), /&lt;svg/);
assert.match(format('2026-10-20 09:00 - Agent - First\n2026-10-20 09:00 - Agent - Second'), /Second[\s\S]*First/);
const entries = [{textContent:'Agent blue wallet'}, {textContent:'Other staff charger'}];
const count = {}, empty = {};
const panel = {querySelectorAll: () => entries, querySelector: selector => selector === '[data-note-count]' ? count : empty};
context.filterTimeline({value:' BLUE ', closest: () => panel});
assert.equal(entries[0].hidden, false); assert.equal(entries[1].hidden, true);
assert.equal(count.textContent, '1 of 2 entries'); assert.equal(empty.hidden, true);
context.filterTimeline({value:'absent', closest: () => panel});
assert.equal(empty.hidden, false);
context.filterTimeline({value:'', closest: () => panel});
assert.ok(entries.every(entry => !entry.hidden));
console.log('History checks passed (escaping, multiline grouping, newest-first order, empty history, search and reset).');
